public class ProfitAndLoss{
    public static void main(String args[]){
        int CP=129;
        int SP=191;
        int profit = SP - CP;
        int profit_percentage = (profit/CP)*100;
        System.out.println("The Cost Price is INR 129 and Selling Price is INR 191"+"The profit is INR"+profit+"and profit percentage is"+profit_percentage+"%");
    }
}